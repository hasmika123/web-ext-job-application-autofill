package com.dossier.api.domain.catalog;

import jakarta.persistence.*;
import java.io.Serializable;
import java.time.Instant;

/**
 * One price of one product for one audience, interval and currency (docs/subscriptions/08-data-model.md section 2.3). Prices are immutable,
 * effective-dated rows: nothing updates {@code amountMinor}; a new price is a new row and the row it replaces is retired. Money is {@code long}
 * minor units plus an ISO currency. At most one row is ACTIVE per (product, audience, interval, currency): {@code activeKey} is a generated column,
 * non-NULL only while {@code active} is true, and carries a UNIQUE index.
 *
 * <p>Lifecycle: DRAFT (created, never published) -> ACTIVE (published and in force) or SCHEDULED (published with a future {@code effectiveFrom}) ->
 * RETIRED. A retired row is never deleted: licenses, add-ons and invoices keep pointing at it and keep being billed at it. Platform data, no org_id.
 */
@Entity
@Table(name = "product_price")
public class ProductPrice implements Serializable {

    private static final long serialVersionUID = 1L;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false)
    private Long id;

    @Column(name = "product_id", nullable = false)
    private Long productId;

    @Column(name = "audience", length = 12, nullable = false)
    private String audience;

    @Column(name = "billing_interval", length = 10, nullable = false)
    private String billingInterval;

    @Column(name = "amount_minor", nullable = false)
    private Long amountMinor;

    @Column(name = "currency", length = 3, columnDefinition = "char(3)", nullable = false)
    private String currency;

    @Column(name = "stripe_price_id", length = 255)
    private String stripePriceId;

    @Column(name = "payout_minor", nullable = false)
    private Long payoutMinor = 0L;

    @Column(name = "subscriber_discount_bp", nullable = false)
    private Integer subscriberDiscountBp = 0;

    @Column(name = "margin_bp_worst")
    private Integer marginBpWorst;

    @Column(name = "margin_bp_typical")
    private Integer marginBpTypical;

    @Column(name = "fee_model_version")
    private Integer feeModelVersion;

    @Column(name = "annual_source", length = 10)
    private String annualSource;

    @Column(name = "derived_from_price_id")
    private Long derivedFromPriceId;

    @Column(name = "derived_discount_bp")
    private Integer derivedDiscountBp;

    @Column(name = "accepts_promos", nullable = false)
    private Boolean acceptsPromos = false;

    @Column(name = "country_set", length = 400)
    private String countrySet;

    @Column(name = "active", nullable = false)
    private Boolean active = false;

    @Column(name = "effective_from", nullable = false)
    private Instant effectiveFrom;

    @Column(name = "effective_until")
    private Instant effectiveUntil;

    @Column(name = "published_at")
    private Instant publishedAt;

    @Column(name = "retired_at")
    private Instant retiredAt;

    @Column(name = "catalog_version", nullable = false)
    private Integer catalogVersion = 0;

    /** Generated by MySQL; never written from here. */
    @Column(name = "active_key", length = 80, insertable = false, updatable = false)
    private String activeKey;

    @Column(name = "created_by", length = 50, nullable = false)
    private String createdBy;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    /** DRAFT, SCHEDULED, ACTIVE or RETIRED, derived from the timestamps and the active flag. */
    @Transient
    public String status() {
        if (retiredAt != null) return "RETIRED";
        if (Boolean.TRUE.equals(active)) return "ACTIVE";
        return publishedAt != null ? "SCHEDULED" : "DRAFT";
    }

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }
    public Long getProductId() { return productId; }
    public void setProductId(Long productId) { this.productId = productId; }
    public String getAudience() { return audience; }
    public void setAudience(String audience) { this.audience = audience; }
    public String getBillingInterval() { return billingInterval; }
    public void setBillingInterval(String billingInterval) { this.billingInterval = billingInterval; }
    public Long getAmountMinor() { return amountMinor; }
    public void setAmountMinor(Long amountMinor) { this.amountMinor = amountMinor; }
    public String getCurrency() { return currency; }
    public void setCurrency(String currency) { this.currency = currency; }
    public String getStripePriceId() { return stripePriceId; }
    public void setStripePriceId(String stripePriceId) { this.stripePriceId = stripePriceId; }
    public Long getPayoutMinor() { return payoutMinor; }
    public void setPayoutMinor(Long payoutMinor) { this.payoutMinor = payoutMinor; }
    public Integer getSubscriberDiscountBp() { return subscriberDiscountBp; }
    public void setSubscriberDiscountBp(Integer subscriberDiscountBp) { this.subscriberDiscountBp = subscriberDiscountBp; }
    public Integer getMarginBpWorst() { return marginBpWorst; }
    public void setMarginBpWorst(Integer marginBpWorst) { this.marginBpWorst = marginBpWorst; }
    public Integer getMarginBpTypical() { return marginBpTypical; }
    public void setMarginBpTypical(Integer marginBpTypical) { this.marginBpTypical = marginBpTypical; }
    public Integer getFeeModelVersion() { return feeModelVersion; }
    public void setFeeModelVersion(Integer feeModelVersion) { this.feeModelVersion = feeModelVersion; }
    public String getAnnualSource() { return annualSource; }
    public void setAnnualSource(String annualSource) { this.annualSource = annualSource; }
    public Long getDerivedFromPriceId() { return derivedFromPriceId; }
    public void setDerivedFromPriceId(Long derivedFromPriceId) { this.derivedFromPriceId = derivedFromPriceId; }
    public Integer getDerivedDiscountBp() { return derivedDiscountBp; }
    public void setDerivedDiscountBp(Integer derivedDiscountBp) { this.derivedDiscountBp = derivedDiscountBp; }
    public Boolean getAcceptsPromos() { return acceptsPromos; }
    public void setAcceptsPromos(Boolean acceptsPromos) { this.acceptsPromos = acceptsPromos; }
    public String getCountrySet() { return countrySet; }
    public void setCountrySet(String countrySet) { this.countrySet = countrySet; }
    public Boolean getActive() { return active; }
    public void setActive(Boolean active) { this.active = active; }
    public Instant getEffectiveFrom() { return effectiveFrom; }
    public void setEffectiveFrom(Instant effectiveFrom) { this.effectiveFrom = effectiveFrom; }
    public Instant getEffectiveUntil() { return effectiveUntil; }
    public void setEffectiveUntil(Instant effectiveUntil) { this.effectiveUntil = effectiveUntil; }
    public Instant getPublishedAt() { return publishedAt; }
    public void setPublishedAt(Instant publishedAt) { this.publishedAt = publishedAt; }
    public Instant getRetiredAt() { return retiredAt; }
    public void setRetiredAt(Instant retiredAt) { this.retiredAt = retiredAt; }
    public Integer getCatalogVersion() { return catalogVersion; }
    public void setCatalogVersion(Integer catalogVersion) { this.catalogVersion = catalogVersion; }
    public String getActiveKey() { return activeKey; }
    public String getCreatedBy() { return createdBy; }
    public void setCreatedBy(String createdBy) { this.createdBy = createdBy; }
    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
}
