package com.dossier.api.service;

import static org.assertj.core.api.Assertions.assertThat;

import com.dossier.api.domain.Interview;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.time.ZoneId;
import java.time.zone.ZoneOffsetTransitionRule;
import java.util.List;
import org.junit.jupiter.api.Test;

/** The .ics export: wall-clock times in the interview's zone, a VTIMEZONE that carries daylight saving, valid folding and escaping. */
class IcsCalendarTest {

    private static final Instant NOW = Instant.parse("2026-10-01T09:30:00Z");
    private static final Instant START = Instant.parse("2026-10-10T14:00:00Z");

    private static Interview interview(String tz) {
        Interview i = new Interview();
        i.setApplicationId(5L);
        i.setUserId(1L);
        i.setKind("VIDEO");
        i.setStartsAt(START);
        i.setTz(tz);
        // the id is generated by the database; set it the way a loaded row would carry it
        org.springframework.test.util.ReflectionTestUtils.setField(i, "id", 7L);
        return i;
    }

    private static String ics(Interview i) {
        return IcsCalendar.interview(i, "Acme", "Backend Engineer", 60, NOW);
    }

    private static List<String> lines(String ics) {
        // unfold: a CRLF followed by one space continues the previous line
        return List.of(ics.replace("\r\n ", "").split("\r\n"));
    }

    @Test
    void anInterviewInNewYorkIsWrittenInItsOwnZoneWithDaylightSavingRules() {
        Interview i = interview("America/New_York");
        i.setLocation("https://meet.example.com/abc");
        i.setInterviewer("Sam Rivera");
        String out = ics(i);
        List<String> l = lines(out);

        assertThat(out).startsWith("BEGIN:VCALENDAR\r\nVERSION:2.0\r\n").endsWith("END:VEVENT\r\nEND:VCALENDAR\r\n");
        assertThat(l).contains("BEGIN:VTIMEZONE", "TZID:America/New_York", "END:VTIMEZONE");
        // second Sunday of March and first Sunday of November, as month days plus a weekday
        assertThat(l).contains(
            "RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=SU;BYMONTHDAY=8,9,10,11,12,13,14",
            "RRULE:FREQ=YEARLY;BYMONTH=11;BYDAY=SU;BYMONTHDAY=1,2,3,4,5,6,7",
            "BEGIN:DAYLIGHT",
            "TZOFFSETFROM:-0500",
            "TZOFFSETTO:-0400",
            "BEGIN:STANDARD",
            "TZOFFSETFROM:-0400",
            "TZOFFSETTO:-0500",
            "DTSTART:19700308T020000",
            "DTSTART:19701101T020000"
        );
        // 14:00Z on Oct 10 is 10:00 in New York (EDT); no end time: one default hour
        assertThat(l).contains(
            "UID:interview-7@kiwiply.com",
            "DTSTAMP:20261001T093000Z",
            "DTSTART;TZID=America/New_York:20261010T100000",
            "DTEND;TZID=America/New_York:20261010T110000",
            "SUMMARY:Interview: Backend Engineer at Acme",
            "LOCATION:https://meet.example.com/abc",
            "URL:https://meet.example.com/abc",
            "STATUS:CONFIRMED"
        );
        assertThat(l).anyMatch(s -> s.startsWith("DESCRIPTION:Video interview\\nInterviewer: Sam Rivera"));
        assertThat(l).noneMatch(s -> s.contains("time zone was not set"));
    }

    @Test
    void everyBeginHasItsEndAndEveryLineIsCrlfTerminated() {
        String out = ics(interview("America/New_York"));
        for (String component : List.of("VCALENDAR", "VTIMEZONE", "VEVENT", "DAYLIGHT", "STANDARD")) {
            assertThat(count(out, "BEGIN:" + component + "\r\n")).as(component).isEqualTo(count(out, "END:" + component + "\r\n"));
        }
        assertThat(out.replace("\r\n", "")).doesNotContain("\n").doesNotContain("\r");
    }

    @Test
    void aZoneWithNoDaylightSavingGetsOneFixedComponent() {
        Interview i = interview("Asia/Kolkata");
        i.setEndsAt(START.plusSeconds(45 * 60));
        List<String> l = lines(ics(i));

        assertThat(l).contains("TZID:Asia/Kolkata", "TZOFFSETFROM:+0530", "TZOFFSETTO:+0530", "BEGIN:STANDARD");
        assertThat(l).noneMatch(s -> s.startsWith("RRULE"));
        assertThat(l).contains("DTSTART;TZID=Asia/Kolkata:20261010T193000", "DTEND;TZID=Asia/Kolkata:20261010T201500");
    }

    @Test
    void noZoneMeansUtcAndSaysSo() {
        List<String> l = lines(ics(interview(null)));
        assertThat(l).contains("DTSTART:20261010T140000Z", "DTEND:20261010T150000Z");
        assertThat(l).noneMatch(s -> s.equals("BEGIN:VTIMEZONE"));
        assertThat(l).anyMatch(s -> s.contains("The time zone was not set"));
        // an unknown stored zone is treated as not set, not as an error
        assertThat(lines(ics(interview("Nowhere/Land")))).contains("DTSTART:20261010T140000Z");
    }

    @Test
    void utcAndBareOffsetsAreWrittenInUtcWithoutAZoneBlock() {
        for (String tz : List.of("UTC", "Z", "+05:00", "Etc/UTC")) {
            List<String> l = lines(ics(interview(tz)));
            assertThat(l).as(tz).contains("DTSTART:20261010T140000Z");
            assertThat(l).as(tz).noneMatch(s -> s.equals("BEGIN:VTIMEZONE"));
            assertThat(l).as(tz + " is a zone the user set").noneMatch(s -> s.contains("time zone was not set"));
        }
    }

    @Test
    void textIsEscapedAndLongLinesAreFoldedWithoutSplittingACharacter() {
        Interview i = interview("UTC");
        i.setLocation("Room 4, Floor 2; HQ\\annex");
        i.setNotes("Line one\nLine two " + "é".repeat(120));
        String out = ics(i);

        assertThat(lines(out)).contains("LOCATION:Room 4\\, Floor 2\\; HQ\\\\annex");
        assertThat(lines(out)).anyMatch(s -> s.startsWith("DESCRIPTION:") && s.contains("Notes: Line one\\nLine two " + "é".repeat(120)));
        for (String physical : out.split("\r\n")) {
            assertThat(physical.getBytes(StandardCharsets.UTF_8).length).as(physical).isLessThanOrEqualTo(75);
        }
        assertThat(out).contains("\r\n "); // something was folded
    }

    @Test
    void summaryDegradesGracefully() {
        assertThat(IcsCalendar.summary("Acme", null)).isEqualTo("Interview at Acme");
        assertThat(IcsCalendar.summary(null, "Engineer")).isEqualTo("Interview: Engineer");
        assertThat(IcsCalendar.summary(" ", " ")).isEqualTo("Interview");
    }

    @Test
    void rruleCoversLastWeekdayRulesAndExactDates() {
        // Europe/London: last Sunday of March / October. The JDK states it as "first Sunday on or after the 25th".
        List<ZoneOffsetTransitionRule> rules = ZoneId.of("Europe/London").getRules().getTransitionRules();
        assertThat(rules).extracting(IcsCalendar::rrule).containsExactlyInAnyOrder(
            "FREQ=YEARLY;BYMONTH=3;BYDAY=SU;BYMONTHDAY=25,26,27,28,29,30,31",
            "FREQ=YEARLY;BYMONTH=10;BYDAY=SU;BYMONTHDAY=25,26,27,28,29,30,31"
        );
    }

    @Test
    void rruleCountsBackFromTheMonthEndWhenTheIndicatorIsNegative() {
        // "the last Sunday on or before the 2nd to last day": month days -8..-2
        ZoneOffsetTransitionRule r = ZoneOffsetTransitionRule.of(
            java.time.Month.MARCH,
            -2,
            java.time.DayOfWeek.SUNDAY,
            java.time.LocalTime.of(2, 0),
            false,
            ZoneOffsetTransitionRule.TimeDefinition.WALL,
            java.time.ZoneOffset.ofHours(1),
            java.time.ZoneOffset.ofHours(1),
            java.time.ZoneOffset.ofHours(2)
        );
        assertThat(IcsCalendar.rrule(r)).isEqualTo("FREQ=YEARLY;BYMONTH=3;BYDAY=SU;BYMONTHDAY=-8,-7,-6,-5,-4,-3,-2");
    }

    @Test
    void offsetsAreSignedFourDigits() {
        assertThat(IcsCalendar.offset(java.time.ZoneOffset.ofHoursMinutes(5, 30))).isEqualTo("+0530");
        assertThat(IcsCalendar.offset(java.time.ZoneOffset.ofHours(-4))).isEqualTo("-0400");
        assertThat(IcsCalendar.offset(java.time.ZoneOffset.UTC)).isEqualTo("+0000");
    }

    private static int count(String haystack, String needle) {
        int n = 0;
        for (int at = haystack.indexOf(needle); at >= 0; at = haystack.indexOf(needle, at + 1)) n++;
        return n;
    }
}
